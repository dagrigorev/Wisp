#!/usr/bin/env python
"""Generate Wisp's full case-folding table from the UCD that uucode ships.

This mirrors uucode's `case_folding_full` field (src/components.zig,
CaseFoldingFull.build): for each codepoint, the status-F mapping from
CaseFolding.txt if there is one, otherwise the status-C mapping, otherwise
the codepoint itself. Status S and T entries are not part of it.

Only codepoints whose folding differs from themselves are emitted, sorted,
so the lookup is a binary search with identity as the fallback.

Usage: gen_case_folding.py <ucd-dir> <out.inc>
"""
import os
import sys

UCD = sys.argv[1]
OUT = sys.argv[2]

common = {}
full = {}
version = ''
with open(os.path.join(UCD, 'CaseFolding.txt'), encoding='utf-8') as f:
    for line in f:
        if line.startswith('# CaseFolding-'):
            version = line[2:].strip()
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        code, status, mapping = [x.strip() for x in line.split(';')[:3]]
        cp = int(code, 16)
        values = [int(x, 16) for x in mapping.split()]
        if status == 'C':
            assert len(values) == 1
            common[cp] = values
        elif status == 'F':
            assert 1 < len(values) <= 3
            full[cp] = values

rows = []
for cp in sorted(set(common) | set(full)):
    mapping = full.get(cp) or common[cp]
    if mapping == [cp]:
        continue
    rows.append((cp, mapping))

with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
    out.write('/* Generated by tools/gen_case_folding.py from %s. Do not edit. */\n' % version)
    out.write('/* { codepoint, mapping length, mapping[3] } sorted by codepoint. */\n')
    for cp, mapping in rows:
        padded = mapping + [0] * (3 - len(mapping))
        out.write('{0x%04X, %d, {0x%04X, 0x%04X, 0x%04X}},\n' % (cp, len(mapping), *padded))

print(version, len(rows), 'entries')
